//# C++ Revision — Pointers & Dynamic Memory
#include <iostream> // مكتبة الإدخال والإخراج
using namespace std; // استخدام cout و cin بدون std::

void fun() { // دالة لتجربة المصفوفة الديناميكية

    // Dynamic Array: إنشاء مصفوفة ديناميكية من 6 عناصر
    int* q = new int[6]; // حجز مساحة بالذاكرة تكفي 6 أعداد صحيحة

    for (int i = 0; i < 6; i++) { // المرور على الفهارس من 0 إلى 5
        cin >> q[i]; // إدخال قيمة وتخزينها في العنصر الحالي
    }

    for (int j = 0; j < 6; j++) { // المرور على عناصر المصفوفة
        cout << q[j] << "  "; // طباعة كل عنصر مع مسافتين
    }

    delete[] q; // تحرير الذاكرة المحجوزة للمصفوفة الديناميكية
} // نهاية الدالة fun

int main() { // نقطة بداية تنفيذ البرنامج

    int x = 1, y = 2, z; // إنشاء متغيرين بقيم ابتدائية ومتغير دون تهيئة

    // Pointers: المؤشرات

    int* p1 = &x; // p1 يخزن عنوان المتغير x

    int* p2; // تعريف مؤشر إلى int دون تهيئته

    p2 = &y; // جعل p2 يخزن عنوان المتغير y

    *p2 = 6; // تعديل القيمة الموجودة في عنوان p2، أي تصبح y = 6

    cout << "x = " << x // طباعة قيمة x
         << " y = " << y // طباعة قيمة y
         << " &x = " << p1 // طباعة عنوان x المخزن في p1
         << " &y = " << p2; // طباعة عنوان y المخزن في p2

    // Dynamic Variable: متغير ديناميكي

    int* p3 = new int(6); // حجز مكان لعدد صحيح قيمته الابتدائية 6

    (*p3)++; // زيادة القيمة التي يشير إليها p3 بمقدار 1، فتصبح 7

    cout << "p3 = " << *p3; // طباعة القيمة 7 وليس عنوانها

    fun(); // استدعاء الدالة لإدخال وطباعة 6 عناصر

    delete p3; // تحرير الذاكرة المحجوزة للمتغير الديناميكي

    p3 = nullptr; // جعل المؤشر لا يشير إلى عنوان بعد تحرير الذاكرة

    return 0; // إنهاء البرنامج بنجاح
}
/*

## أهم الأفكار في الكود

### 1. الفرق بين `p1` و `*p1` و `&x`

| التعبير | معناه |
|---|---|
| `x` | قيمة المتغير، وهي `1` |
| `&x` | عنوان المتغير `x` في الذاكرة |
| `p1` | العنوان المخزن في المؤشر، وهو عنوان `x` |
| `*p1` | القيمة الموجودة في العنوان الذي يشير إليه `p1` |

مثال:

```cpp
int x = 1;
int* p1 = &x;

cout << p1;  // يطبع عنوان x
cout << *p1; // يطبع 1

*p1 = 10;    // تصبح قيمة x تساوي 10
```

### 2. لماذا أصبحت `y = 6`؟

```cpp
int y = 2;
int* p2 = &y;
*p2 = 6;
```

لأن `p2` يشير إلى `y`، وكتابة `*p2 = 6` تعني تعديل قيمة `y` نفسها.

### 3. الفرق بين `new` و `delete`

```cpp
int* p3 = new int(6);
delete p3;
```

- `new int(6)`: يحجز ذاكرة لمتغير واحد قيمته الابتدائية 6.
- `delete p3`: يحرر الذاكرة المحجوزة لهذا المتغير.

أما المصفوفة:

```cpp
int* q = new int[6];
delete[] q;
```

استخدمنا `delete[]` لأننا حجزنا **مصفوفة كاملة**.

### 4. الفرق بين `q[i]` و `*(q + i)`

في المصفوفة الديناميكية، هذان التعبيران متكافئان:

```cpp
q[i]
*(q + i)
```

كلاهما يصل إلى العنصر رقم `i`.

### 5. ماذا يحدث عند استدعاء `fun()`؟

1. يحجز البرنامج مساحة لستة أعداد صحيحة.
2. يطلب منك إدخال ست قيم.
3. يطبع القيم الست بالترتيب.
4. يحرر الذاكرة باستخدام `delete[] q`.

**ملاحظة:** المتغير `z` غير مستخدم في البرنامج، وكذلك لا توجد حاجة إلى تغيير قيمة `p3` إلى `nullptr` بعد `delete` إلا إذا أردت تجنب ترك المؤشر يحمل عنوانًا قديمًا؛ لكنها ممارسة جيدة.
*/
